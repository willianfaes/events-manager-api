-- Transactional outbox: a row is written in the same transaction as the registration change and published to the
-- broker later. Not a domain table, so no is_deleted: a row only goes from pending (sent_at NULL) to sent.
CREATE TABLE outbox_messages
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id  UUID        NOT NULL UNIQUE,
    type        VARCHAR(50) NOT NULL,
    message_key VARCHAR(50) NOT NULL,
    payload     JSONB       NOT NULL,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at     TIMESTAMP
);

-- The publisher only reads pending rows, in id order.
CREATE INDEX idx_outbox_messages_pending ON outbox_messages (id) WHERE sent_at IS NULL;
