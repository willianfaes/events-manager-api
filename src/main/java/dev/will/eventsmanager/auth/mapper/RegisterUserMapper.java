package dev.will.eventsmanager.auth.mapper;

import dev.will.eventsmanager.auth.dto.request.RegisterUserRequest;
import dev.will.eventsmanager.auth.dto.response.RegisterUserResponse;
import dev.will.eventsmanager.users.entity.User; // Assuming User entity is in dev.will.events.entity
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.ReportingPolicy;

@Mapper(
        componentModel = "spring",
        unmappedTargetPolicy = ReportingPolicy.WARN
)
public interface RegisterUserMapper {

    /**
     * Maps a RegisterUserRequest DTO to a User entity.
     * The 'id' field of the User entity will be auto-generated by the persistence layer.
     */
    @Mapping(target = "id", ignore = true) // ID is auto-generated
    User toEntity(RegisterUserRequest request);

    /**
     * Maps a User entity to a RegisterUserResponse DTO.
     */

    @Mapping(target = "userId", source = "id")
    RegisterUserResponse toResponse(User user);
}